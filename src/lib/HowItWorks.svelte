  <div class="section-head">
    <p class="eyebrow">操作指南</p>
    <h2 id="how-heading">如何清除照片中的隐藏元数据与内容凭证</h2>
    <p>
      仅需简单三步，无需注册账号，也无需上传文件。所有处理完全在您的设备本地完成，照片绝不会发送到任何服务器。
    </p>
  </div>

  <ol class="howto">
    <li>
      <h3>添加图片</h3>
      <p>
        将 JPEG、PNG、TIFF、HEIC 或 AVIF 文件拖入工具框，或从设备中选择文件，也可以直接粘贴剪贴板中的图片。
      </p>
    </li>
    <li>
      <h3>查看隐藏信息</h3>
      <p>
        AiUntrace 会列出检测到的每一个元数据模块——包括 C2PA 内容凭证、AI 生成标记、GPS 坐标、相机参数与时间戳。
      </p>
    </li>
    <li>
      <h3>清除并下载</h3>
      <p>
        图片会被解码为纯像素并重新编码输出，从而彻底丢弃所有元数据容器。核验无残留后即可下载纯净副本。
      </p>
    </li>
  </ol>
